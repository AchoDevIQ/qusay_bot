export type TestMark = { state: "ok" | "bad"; rev: number; note?: string; at: string };
export type TestMarks = Record<string, TestMark>;
export const stepKey = (section: string, step: string) => `${section}.${step}`;
/** حالة الخطوة: مؤشرة بنفس النسخة، أو تغيرت من وكت ما تأشرت، أو ما تجربت */
export function stepState(step: TestStep, mark?: TestMark): "ok" | "bad" | "changed" | "todo" {
  if (!mark) return "todo";
  return mark.rev === (step.rev ?? 1) ? mark.state : "changed";
}
