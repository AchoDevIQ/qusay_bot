"use client";
// 📖 شرح الامتحان بالآيباد (طلبه 2026-11-28: «خليه مخزون له حتى إذا احتاج يشوفه، ودائماً يتحدث»).
// هذا المكان الوحيد للشرح: شاشة أول امتحان، زر «📖» بامتحاناتي، وزر «📖 الشرح» بورقة القلم كلهن يقرن من هنا.
// أي تغيير بامتحان الآيباد (الحضور، فتح الأسئلة، الإرسال، التسليم) لازم يتحدث هنا وياه.
import { useState } from "react";

/** خطوات الإرسال والتسليم بورقة القلم (تطلع بشاشة أول امتحان، وجوه الشرح الكامل) */
function SendSteps() {
  return (
    <ol>
      <li><b>اكتب جوابك</b> بكل ورقة، ومن تخلصها دوس <b>«✅ تم»</b>. رقم السؤال فوگ يصير <b className="ok">أخضر</b> (الأحمر يعني بعده ما خلص).</li>
      <li>من تخلص كل الأسئلة دوس الزر الكبير <b>«✅ أكملت الجواب على جميع الأسئلة»</b>. هذا ما يرسل شي، بس يوريك أسئلتك.</li>
      <li>تطلعلك كل الأسئلة: <b className="ok">✅ مكتوب</b> لو <b className="no">⚠️ فارغ</b>. إذا نسيت سؤال دوس عليه وارجع اكتبه.</li>
      <li>من تتأكد دوس <b>«📤 أرسل الأجوبة وسلّم»</b>: كل أجوبتك تنرسل مرة وحدة، وبعدها ما تگدر تغير.</li>
    </ol>
  );
}

/** الشرح: part="send" خطوات الإرسال بس (وقت الامتحان)، وبدونه الشرح كله من البيت للتسليم */
export function IpadGuide({ part }: { part?: "send" }) {
  if (part === "send") {
    return (
      <>
        <SendSteps />
        <div className="exhint">⏳ الوقت يمشي من فتحت الأسئلة. إذا خلص الوقت، اللي كتبته ينرسل وحده.</div>
      </>
    );
  }
  return (
    <>
      <h3>🏠 قبل يوم الامتحان</h3>
      <ol>
        <li>بصفحة «امتحاناتي» دوس <b>«📱 أمتحن بالآيباد»</b>.</li>
        <li>حسابك يشتغل على جهاز واحد، فافتح التطبيق كله من <b>الآيباد</b> مو من الموبايل.</li>
        <li>اشحن الآيباد والقلم، وتأكد الانترنت يشتغل عليه.</li>
      </ol>
      <h3>🏫 من توصل المركز</h3>
      <ol>
        <li>افتح التطبيق بالآيباد، وروح لـ<b>«امتحاناتي»</b>. تلگى فوگ <b>«🎫 كود الحضور»</b>.</li>
        <li>طلّع الكود (من شاشة الآيباد نفسه) للمساعد. جهاز الحضور يقراه وينسجل حضورك. ما تنطبعلك ورقة.</li>
        <li><b>خلي صفحة «امتحاناتي» مفتوحة</b> بالآيباد: خلال ثواني أسئلتك تنفتح وحدها، وما تحتاج تدوس شي.</li>
        <li>إذا ما انفتحت، سد الصفحة وافتحها مرة ثانية. والأسئلة ما تنفتح من الموبايل، بس من الآيباد.</li>
      </ol>
      <h3>✏️ وقت الامتحان</h3>
      <SendSteps />
      <div className="exhint">⏳ الوقت يمشي من تنفتح الأسئلة. إذا خلص الوقت، اللي كتبته ينرسل وحده. والورقة اللي ما كتبت بيها ولا شي تاخذ صفر.</div>
    </>
  );
}

/** زر «📖 شرح الامتحان بالآيباد»: يفتح الشرح كله فوگ الصفحة، ويرجع يتسكر */
export function IpadGuideButton({ part, label = "📖 شرح الامتحان بالآيباد", className = "exbtn" }: { part?: "send"; label?: string; className?: string }) {
  const [open, setOpen] = useState(false);
  return (
    <>
      <button type="button" className={className} onClick={() => setOpen(true)}>{label}</button>
      {open && (
        <div className="pen-done" onClick={() => setOpen(false)}>
          <div className="card agcard pen-intro pen-guide" onClick={(e) => e.stopPropagation()}>
            <h2>📖 شرح الامتحان بالآيباد</h2>
            <IpadGuide part={part} />
            <button type="button" className="btn agbtn" onClick={() => setOpen(false)}>✅ تمام، سدّ الشرح</button>
          </div>
        </div>
      )}
    </>
  );
}
